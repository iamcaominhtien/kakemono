"""scripts/release.py: the version a pull request must carry, and its entry."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import release

BODY = """## Summary

Turning the cover showed the next page at once.

### How

- `begin()` hides the left side.

## Testing

cargo test

---
_Generated by [Claude Code](https://claude.ai/code)_
"""


def test_the_title_sets_the_version():
    def want(title):
        return release.bump("0.13.1", release.level(release.parse(title)))

    assert want("fix(book): x") == "0.13.2"
    assert want("docs: x") == "0.13.2"  # every PR is released
    assert want("feat: x") == "0.14.0"
    assert want("feat!: x") == "0.14.0"  # 0.x: breaking bumps the minor
    assert release.bump("1.2.3", release.level(release.parse("fix: x", "BREAKING CHANGE: y"))) == "2.0.0"


def test_a_pull_request_must_carry_its_version():
    fix = release.parse("fix: x")
    assert release.verdict("0.13.1", "0.13.2", fix) is None
    assert "0.13.2" in release.verdict("0.13.1", "0.13.1", fix)
    assert release.verdict("0.13.1", "1.0.0", fix) is None  # set by hand


def test_the_description_is_cleaned_for_users():
    text = release.clean(BODY)
    assert text.startswith("Turning the cover")
    assert "##### How" in text
    assert "Testing" not in text and "Generated by" not in text


def test_the_entry_goes_on_top_and_a_new_bump_replaces_it():
    existing = "# Changelog\n\n## [Unreleased]\n## [0.13.1](link) - 2026-11-20\n\n### Fixed\n\n- old\n"
    first = release.entry(release.parse("feat(book): a", BODY, 21), "0.14.0", "0.13.1", "2026-11-22")
    assert first.startswith("## [0.14.0](https://github.com/iamcaominhtien/kakemono/compare/v0.13.1...v0.14.0) - 2026-11-22")
    assert "- *(book)* A ([#21](https://github.com/iamcaominhtien/kakemono/pull/21))" in first
    once = release.changelog(existing, "0.14.0", first, "0.13.1")
    second = release.entry(release.parse("fix(book): a", BODY, 21), "0.13.2", "0.13.1", "2026-11-22")
    twice = release.changelog(once, "0.13.2", second, "0.13.1")
    assert "0.14.0" not in twice
    assert twice.index("## [0.13.2]") < twice.index("## [0.13.1]")
    assert release.section(twice, "0.13.1") == "### Fixed\n\n- old\n"


def test_the_version_files_agree():
    assert len(set(release.versions(release.ROOT).values())) == 1
