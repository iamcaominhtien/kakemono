"""scripts/release.py: the version a pull request must carry, and its entry."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import release

BODY = """## Summary

Turning the cover showed the next page at once.

### How

- `begin()` hides the left side.

## Testing

cargo test

---
_Generated by [Claude Code](https://claude.ai/code)_
"""


def test_the_title_sets_the_version():
    def want(title):
        return release.bump("0.13.1", release.level(release.parse(title)))

    assert want("fix(book): x") == "0.13.2"
    assert want("docs: x") == "0.13.2"  # every PR is released
    assert want("feat: x") == "0.14.0"
    assert want("feat!: x") == "0.14.0"  # 0.x: breaking bumps the minor
    assert release.bump("1.2.3", release.level(release.parse("fix: x", "BREAKING CHANGE: y"))) == "2.0.0"


def test_a_pull_request_must_carry_its_version():
    fix = release.parse("fix: x")
    assert release.verdict("0.13.1", "0.13.2", fix) is None
    assert "0.13.2" in release.verdict("0.13.1", "0.13.1", fix)
    assert release.verdict("0.13.1", "1.0.0", fix) is None  # set by hand


def test_the_description_is_cleaned_for_users():
    text = release.clean(BODY)
    assert text.startswith("Turning the cover")
    assert "##### How" in text
    assert "Testing" not in text and "Generated by" not in text


def test_the_entry_goes_on_top_and_a_new_bump_replaces_it():
    existing = "# Changelog\n\n## [Unreleased]\n## [0.13.1](link) - 2026-11-20\n\n### Fixed\n\n- old\n"
    first = release.entry(release.parse("feat(book): a", BODY, 21), "0.14.0", "0.13.1", "2026-11-22")
    assert first.startswith("## [0.14.0](https://github.com/iamcaominhtien/kakemono/compare/v0.13.1...v0.14.0) - 2026-11-22")
    assert "- *(book)* A ([#21](https://github.com/iamcaominhtien/kakemono/pull/21))" in first
    once = release.changelog(existing, "0.14.0", first, "0.13.1")
    second = release.entry(release.parse("fix(book): a", BODY, 21), "0.13.2", "0.13.1", "2026-11-22")
    twice = release.changelog(once, "0.13.2", second, "0.13.1")
    assert "0.14.0" not in twice
    assert twice.index("## [0.13.2]") < twice.index("## [0.13.1]")
    assert release.section(twice, "0.13.1") == "### Fixed\n\n- old\n"


def test_the_version_files_agree():
    assert len(set(release.versions(release.ROOT).values())) == 1


def test_the_description_file_is_read_only_from_the_repository_or_a_temporary_directory(tmp_path, monkeypatch):
    note = tmp_path / "body.md"
    note.write_text("text", encoding="utf-8")
    assert release.read_body(str(note)) == "text"
    assert release.read_body(None) == ""
    assert release.read_body(str(release.ROOT / "CHANGELOG.md")).startswith("# Changelog")
    monkeypatch.setattr(sys, "stdin", __import__("io").StringIO("from stdin"))
    assert release.read_body("-") == "from stdin"
    for outside in ("/etc/passwd", str(release.ROOT / ".." / "elsewhere.md")):
        try:
            release.read_body(outside)
        except SystemExit:
            continue
        raise AssertionError(f"{outside} was read")


def test_a_pull_request_number_is_a_positive_integer():
    for bad in (0, -3):
        try:
            release.pull_request(bad)
        except SystemExit as e:
            assert "not a pull request number" in str(e)
            continue
        raise AssertionError(f"{bad} was accepted")


def test_gh_is_asked_for_the_pull_request(monkeypatch):
    seen = []

    def run(cmd, **kwargs):
        seen.append(cmd)
        return __import__("subprocess").CompletedProcess(cmd, 0, stdout='{"title": "fix: a", "body": "b"}', stderr="")

    monkeypatch.setattr(release.subprocess, "run", run)
    assert release.pull_request(28) == ("fix: a", "b")
    assert seen == [["gh", "pr", "view", "28", "--json", "title,body"]]


def test_bump_and_check_read_the_description_file(tmp_path, monkeypatch):
    import argparse
    import shutil

    for name in ("Cargo.toml", "Cargo.lock", "CHANGELOG.md"):
        shutil.copy(release.ROOT / name, tmp_path / name)
    note = tmp_path / "body.md"
    note.write_text("The cover turns.\n", encoding="utf-8")
    monkeypatch.setattr(release, "ROOT", tmp_path)
    monkeypatch.setattr(release, "last_release", lambda ref=release.MAIN: "0.1.0")
    args = argparse.Namespace(title="feat(book): turn the cover", body_file=str(note), pr=21)
    assert release.cmd_bump(args) == 0
    assert set(release.versions(tmp_path).values()) == {"0.2.0"}
    assert "The cover turns." in (tmp_path / "CHANGELOG.md").read_text(encoding="utf-8")
    assert release.cmd_check(args) == 0
