"""Versions and release notes of kakemono, set in each pull request: the merged
commit of a pull request is the release, tagged by the Release workflow
(CONTRIBUTING.md has the rules).

Every pull request is released. Its title (a Conventional Commits subject, kept
by squash merging) sets the version against the last release tag:

- a breaking change (`feat!:`, `fix!:`, or "BREAKING CHANGE" in the
  description) bumps the major version, the minor one while the major is 0;
- `feat:` bumps the minor version;
- anything else bumps the patch version.

A version set by hand above that (a jump to 1.0.0) is accepted.

    python3 scripts/release.py bump --pr 12          # in a PR: write the version and the CHANGELOG.md entry
    python3 scripts/release.py bump --title "feat: x" --body-file desc.md   # the same without GitHub
    python3 scripts/release.py check --title T --body-file F   # CI: the PR holds the version its title asks for
    python3 scripts/release.py notes VERSION          # the CHANGELOG.md entry of VERSION (the release's notes)
    python3 scripts/release.py version                # the version in Cargo.toml

The entry of a release is the PR's title, under its group (Added, Fixed, ...),
followed by its description, cleaned of what is only for reviewers (a Summary
heading, the Testing sections, the "Generated by" footer, trailers), with its
headings moved two levels down.
"""

import argparse
import datetime
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
#: The repository, for the links of the changelog.
REPO = "iamcaominhtien/kakemono"
#: The branch releases are made from.
MAIN = "origin/main"
#: Files that hold the version, with the pattern of the line that holds it.
VERSION_FILES = {
    "Cargo.toml": r'(?m)\A(?:(?!^\[dependencies).)*?^(version = ")([^"]+)(")',
    "Cargo.lock": r'(?m)^(name = "kakemono"\nversion = ")([^"]+)(")',
}
CHANGELOG = "CHANGELOG.md"
#: The line after which a new entry goes.
UNRELEASED = "## [Unreleased]\n"
#: A Conventional Commits title: `kind(scope)!: subject`.
TITLE = re.compile(r"^(?P<kind>[a-z]+)(?:\((?P<scope>[^)]*)\))?(?P<bang>!)?:\s*(?P<subject>.+)$")
#: The number of the pull request a squash commit came from: `subject (#12)`.
PR_NUMBER = re.compile(r"\s*\(#(\d+)\)\s*$")
#: A version entry of CHANGELOG.md: `## [1.2.3](link) - 2026-11-22`.
ENTRY = re.compile(r"(?m)^## \[(?P<version>\d+\.\d+\.\d+)\][^\n]*\n")
#: Changelog groups, by kind of change.
GROUPS = {
    "feat": "Added",
    "fix": "Fixed",
    "perf": "Performance",
    "refactor": "Changed",
    "style": "Changed",
    "docs": "Documentation",
    "test": "Tests",
    "ci": "Build and CI",
    "build": "Build and CI",
}
#: Parts of a PR description that are for reviewers only, removed from the notes.
REVIEW_ONLY = [
    (r"(?s)\n+---\n+_Generated by.*", ""),
    (r"(?m)^🤖 Generated with.*\n?", ""),
    (r"(?m)^https://claude\.ai/code/session_\S*\n?", ""),
    (r"(?m)^(Co-authored-by|Co-Authored-By|Claude-Session|Signed-off-by): .*\n?", ""),
    (r"(?m)^#{1,3} Summary\n+", ""),
    (r"(?s)\n#{1,3} (Testing|Tests|Test plan|Verification|Snapshots)\n.*?(?=\n#{1,3} |\Z)", ""),
]


@dataclass
class Change:
    """One pull request."""

    title: str
    #: The Conventional Commits kind (`feat`, `fix`, ...), or "other".
    kind: str = "other"
    scope: str = ""
    breaking: bool = False
    #: The subject of the title, without its kind and scope.
    subject: str = ""
    #: The pull request's number, or None when it is not known.
    number: int | None = None
    #: Its description, as it goes into the notes.
    body: str = ""


def clean(body: str) -> str:
    """A PR description as release notes: without what is for reviewers only,
    without HTML comments, its headings two levels down."""
    text = re.sub(r"<!--.*?-->", "", body or "", flags=re.S).replace("\r\n", "\n")
    text = "\n" + text
    for pattern, replacement in REVIEW_ONLY:
        text = re.sub(pattern, replacement, text)
    text = re.sub(r"(?m)^(#{1,3}) ", r"##\1 ", text)
    return text.strip()


def parse(title: str, body: str = "", number: int | None = None) -> Change:
    """The change a pull request title (and description) describes; a title
    that ends with `(#N)`, as a squash commit does, gives the number."""
    m = PR_NUMBER.search(title)
    if m and number is None:
        number = int(m.group(1))
    title = PR_NUMBER.sub("", title).strip()
    m = TITLE.match(title)
    if not m:
        return Change(title=title, subject=title, number=number, body=clean(body))
    return Change(
        title=title,
        kind=m.group("kind"),
        scope=m.group("scope") or "",
        breaking=bool(m.group("bang")) or "BREAKING CHANGE" in body or "BREAKING-CHANGE" in body,
        subject=m.group("subject").strip(),
        number=number,
        body=clean(body),
    )


def parse_version(version: str) -> tuple[int, int, int]:
    """`"1.2.3"` as `(1, 2, 3)`."""
    major, minor, patch = (int(x) for x in version.split("."))
    return major, minor, patch


def level(change: Change) -> str:
    """The part of the version a change bumps: "major", "minor" or "patch"."""
    if change.breaking:
        return "major"
    return "minor" if change.kind == "feat" else "patch"


def bump(version: str, part: str) -> str:
    """`version` bumped by `part`; a breaking change bumps the minor version
    while the major version is 0."""
    major, minor, patch = parse_version(version)
    if part == "major" and major == 0:
        part = "minor"
    if part == "major":
        return f"{major + 1}.0.0"
    if part == "minor":
        return f"{major}.{minor + 1}.0"
    return f"{major}.{minor}.{patch + 1}"


def verdict(released: str, current: str, change: Change) -> str | None:
    """What is wrong with the version `current` of a pull request, or None.
    A version above the expected one is accepted (a version set by hand)."""
    want = bump(released, level(change))
    if current == want or parse_version(current) > parse_version(want):
        return None
    return f"the title “{change.title}” makes this release {want} (the version is {current})"


def entry(change: Change, version: str, previous: str, date: str) -> str:
    """The CHANGELOG.md entry of a release made of one pull request."""
    scope = f"*({change.scope})* " if change.scope else ""
    breaking = "[**breaking**] " if change.breaking else ""
    subject = change.subject[:1].upper() + change.subject[1:]
    link = f" ([#{change.number}](https://github.com/{REPO}/pull/{change.number}))" if change.number else ""
    group = "Breaking changes" if change.breaking and change.kind not in GROUPS else GROUPS.get(change.kind, "Other")
    text = f"## [{version}](https://github.com/{REPO}/compare/v{previous}...v{version}) - {date}\n\n### {group}\n\n"
    text += f"- {scope}{breaking}{subject}{link}\n"
    if change.body:
        text += "\n" + change.body + "\n"
    return text


def changelog(existing: str, version: str, text: str, released: str) -> str:
    """CHANGELOG.md with `text` as the newest entry, in place of an entry not
    released yet (above `released`) that an earlier bump of the PR wrote."""
    if UNRELEASED not in existing:
        raise SystemExit(f"{CHANGELOG} has no '{UNRELEASED.strip()}' line")
    head, rest = existing.split(UNRELEASED, 1)
    first = ENTRY.match(rest)
    if first and parse_version(first.group("version")) > parse_version(released):
        following = ENTRY.search(rest, first.end())
        rest = rest[following.start() :] if following else ""
    return head + UNRELEASED + text + ("\n" if rest and not text.endswith("\n\n") else "") + rest


def section(text: str, version: str) -> str | None:
    """The body of the CHANGELOG.md entry of `version`, or None."""
    for m in ENTRY.finditer(text):
        if m.group("version") == version:
            following = ENTRY.search(text, m.end())
            return text[m.end() : following.start() if following else len(text)].strip() + "\n"
    return None


def set_version(root: Path, version: str) -> None:
    """Writes `version` into every file of VERSION_FILES."""
    for name, pattern in VERSION_FILES.items():
        path = root / name
        text = path.read_text(encoding="utf-8")
        new, count = re.subn(pattern, lambda m: m.group(0)[: m.start(2) - m.start(0)] + version + m.group(3), text, count=1, flags=re.S)
        if count != 1:
            raise SystemExit(f"no version line in {name}")
        path.write_text(new, encoding="utf-8")


def versions(root: Path) -> dict[str, str]:
    """The version written in each file of VERSION_FILES."""
    out = {}
    for name, pattern in VERSION_FILES.items():
        m = re.search(pattern, (root / name).read_text(encoding="utf-8"), flags=re.S)
        out[name] = m.group(2) if m else ""
    return out


def _git(*args: str) -> str:
    """The output of a git command run at the root of the repository."""
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout


def last_release(ref: str = MAIN) -> str:
    """The version of the last release reachable from `ref` (its `vX.Y.Z` tag)."""
    tags = [t for t in _git("tag", "--merged", ref, "--list", "v*").split() if re.fullmatch(r"v\d+\.\d+\.\d+", t)]
    if not tags:
        raise SystemExit(f"no vX.Y.Z tag reachable from {ref}")
    return max((t[1:] for t in tags), key=parse_version)


def pull_request(number: int) -> tuple[str, str]:
    """A pull request's title and description, read with `gh`."""
    result = subprocess.run(["gh", "pr", "view", str(number), "--json", "title,body"], cwd=ROOT, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise SystemExit(f"gh cannot read PR #{number}: {result.stderr.strip()} (give --title and --body-file instead)")
    data = json.loads(result.stdout)
    return data["title"], data.get("body") or ""


def cmd_bump(args: argparse.Namespace) -> int:
    """Writes the version a pull request's title asks for, and its entry."""
    if args.title:
        title = args.title
        body = Path(args.body_file).read_text(encoding="utf-8") if args.body_file else ""
    else:
        title, body = pull_request(args.pr)
    change = parse(title, body, args.pr)
    released = last_release()
    version = bump(released, level(change))
    set_version(ROOT, version)
    path = ROOT / CHANGELOG
    text = entry(change, version, released, datetime.date.today().isoformat())
    path.write_text(changelog(path.read_text(encoding="utf-8"), version, text, released), encoding="utf-8")
    print(f"version {version} ({level(change)} after {released}); entry in {CHANGELOG}")
    return 0


def cmd_check(args: argparse.Namespace) -> int:
    """Fails when the pull request does not hold the version its title asks
    for, or when the files disagree."""
    body = Path(args.body_file).read_text(encoding="utf-8") if args.body_file else ""
    change = parse(args.title, body)
    found = versions(ROOT)
    problems = []
    if len(set(found.values())) != 1:
        problems.append("the version files disagree: " + ", ".join(f"{k} {v}" for k, v in found.items()))
    current = found["Cargo.toml"]
    released = last_release()
    problem = verdict(released, current, change)
    if problem:
        problems.append(problem)
    elif section((ROOT / CHANGELOG).read_text(encoding="utf-8"), current) is None:
        problems.append(f"{CHANGELOG} has no entry for {current}")
    if problems:
        for p in problems:
            print(f"::error::{p}")
        print("Run: python3 scripts/release.py bump --pr <number>, then commit and push.")
        return 1
    print(f"version {current}: ok (last release {released})")
    return 0


def main() -> int:
    """Runs one of the commands of the module's docstring."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("bump", help="write the version a PR's title asks for, and its CHANGELOG.md entry")
    p.add_argument("--pr", type=int, help="the pull request's number (its title and description are read with gh)")
    p.add_argument("--title", help="the PR title, instead of reading it with gh")
    p.add_argument("--body-file", help="the PR description, with --title")
    p = sub.add_parser("check", help="fail unless the version is the one the PR title asks for")
    p.add_argument("--title", required=True)
    p.add_argument("--body-file", help="the PR description")
    p = sub.add_parser("notes", help="print the CHANGELOG.md entry of a version")
    p.add_argument("version")
    sub.add_parser("version", help="print the version in Cargo.toml")
    args = parser.parse_args()
    if args.command == "bump":
        if not args.pr and not args.title:
            parser.error("bump needs --pr or --title")
        return cmd_bump(args)
    if args.command == "check":
        return cmd_check(args)
    if args.command == "notes":
        text = section((ROOT / CHANGELOG).read_text(encoding="utf-8"), args.version)
        if text is None:
            raise SystemExit(f"no entry for {args.version} in {CHANGELOG}")
        print(text, end="")
        return 0
    print(versions(ROOT)["Cargo.toml"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
